<?php
function soma($num1, $num2)
{
    $resultado = $num1 + $num2;
    return $resultado;
}
function subtracao($num1, $num2)
{
    $resultado = $num1 - $num2;
    return $resultado;
}
function multiplicacao($num1, $num2)
{
    $resultado = $num1 * $num2;
    return $resultado;
}
function divisao($num1, $num2)
{
    $resultado = $num1 / $num2;
    return $resultado;
}
